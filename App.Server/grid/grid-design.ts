/**
 * Loads the "design" plane: the design band grid (GridPlaneDto.grids[0]),
 * the Properties grid (grids[1]) with the PropertyDto rows of the band selected in grids[0], or of the cell selected in grids[2] (no rows if no band is selected)
 * and the Form grid (grids[2]) previewing the selected band if it is a ContentBandEnum.Form.
 */
export async function planeDesignLoad(request: Request, gridPlaneDto: GridPlaneDto): Promise<GridPlaneDto> {
  // The Properties and Form grids depend on the reloaded design band grid (its selected row), so they are built afterwards.
  const gridDto = await gridDesignBandLoad(request, gridPlaneDto.grids?.[0] ?? {});
  const band = await gridDesignBandSelectedLoad(request, gridDto);
  const formGridDtoIn = gridPlaneDto.grids?.[2] ?? {};
  const cell = await gridDesignFormSelectedLoad(request, band, formGridDtoIn);
  // The Form grid is built after the Properties grid, which saves and syncs the properties it reads.
  const propertyGridDto = await gridDesignBandFormPropertyLoad(request, gridPlaneDto.grids?.[1] ?? {}, band, cell);
  const formGridDto = await gridDesignFormLoad(request, band, formGridDtoIn);
  return { ...gridPlaneDto, grids: [gridDto, propertyGridDto, formGridDto] };
}

/** Parses a RowCount or ColumnCount propertyValue, clamped to 0..50 (empty or invalid is 0), like Content.tsx. */
function designFormCount(text: string | undefined): number {
  const value = Number((text ?? '').trim());
  return Number.isInteger(value) ? Math.min(Math.max(value, 0), 50) : 0;
}

/** Returns the column names (A, B, C, ... by indexToColumnNameExcel) and the row count of the Form grid of band; none if band is not a ContentBandEnum.Form. */
async function gridDesignFormSize(request: Request, band: DesignBandDto | undefined): Promise<{ columnNames: string[]; rowCount: number }> {
  const properties = band?.bandEnum === ContentBandEnum.Form && band.name ? await designBandPropertyLoad(request, band.name) : [];
  const propertyValue = (propertyName: string) => properties.find((property) => property.propertyName === propertyName)?.propertyValue;
  const rowCount = designFormCount(propertyValue('RowCount'));
  const columnCount = designFormCount(propertyValue('ColumnCount'));
  return { columnNames: Array.from({ length: columnCount }, (_, columnIndex) => indexToColumnNameExcel(columnIndex)), rowCount };
}

/** A selected cell of the Form grid. */
interface DesignFormCell {
  rowIndex: number;
  columnName: string;
}

/** Returns the selected cell of the Form grid gridDto, or undefined if none is selected or it isn't in the form of band (anymore). */
async function gridDesignFormSelectedLoad(request: Request, band: DesignBandDto | undefined, gridDto: GridDto): Promise<DesignFormCell | undefined> {
  const rowIndex = gridDto.state?.selectedRowIndex;
  const columnName = gridDto.state?.selectedColumnName;
  if (rowIndex === undefined || columnName === undefined) {
    return undefined;
  }
  const { columnNames, rowCount } = await gridDesignFormSize(request, band);
  return rowIndex < rowCount && columnNames.includes(columnName) ? { rowIndex, columnName } : undefined;
}

/**
 * Builds the Form grid: if band is a ContentBandEnum.Form, ColumnCount header columns (named A, B, C, ... by indexToColumnNameExcel)
 * and RowCount rows (each cell "Hello"); otherwise no columns and no rows. Read only, so no find row, sort, paging, Save or Reload.
 * The selected cell of gridDto is kept if it is still in the form.
 */
async function gridDesignFormLoad(request: Request, band: DesignBandDto | undefined, gridDto: GridDto): Promise<GridDto> {
  const { columnNames, rowCount } = await gridDesignFormSize(request, band);

  // No columnName on the header cells: clicking them doesn't sort and they have no filter button.
  const headerRow: GridRowDto = { cells: columnNames.map((columnName) => gridHeaderCell(undefined, undefined, columnName)) };
  // rowIndex and columnName make a clicked cell selectable; its Select (isSelectPatch, isSelectColumnPatch) shows the cell's properties in the Properties grid.
  const rows: GridRowDto[] = Array.from({ length: rowCount }, (_, rowIndex) => ({
    cells: columnNames.map((columnName): GridCellDto => ({ cellEnum: GridCellEnum.Label, text: 'Hello', rowIndex, columnName })),
  }));

  const cell = await gridDesignFormSelectedLoad(request, band, gridDto);

  return {
    title: 'Design Form',
    tables: gridTables([], columnNames.length > 0 ? [headerRow, ...rows] : []),
    state: cell !== undefined ? { selectedRowIndex: cell.rowIndex, selectedColumnName: cell.columnName } : {},
    setting: { isSelectPatch: true, isSelectColumnPatch: true },
  };
}

/**
 * Loads the CONTENT_FORM_PLANE_NAME plane (a ContentBandEnum.Form band of Content.tsx): one read only grid (grids[0]) with ColumnCount header columns
 * (named A, B, C, ... by indexToColumnNameExcel) and RowCount rows (each cell the FieldName property of that cell of the Form band named by GridStateDto.custom's
 * bandName, "Cell" if missing or empty), each followed by a row of their values (the value of that FieldName of the DynamicDto row, "Empty" if the cell has no
 * FieldName), repeated for each DynamicDto row of the current page (every cell's rowIndex is that row's index on the page), the counts taken from its GridStateDto.custom
 * (clamped like designFormCount),
 * followed by the bar (New, Save, Reload and pager). The pager pages the DynamicDto rows of GridStateDto.custom's tableName (all rows if missing or empty, like the
 * Data grid of the "dynamic" plane). New and Save don't do anything yet.
 */
export async function planeContentFormLoad(request: Request, gridPlaneDto: GridPlaneDto): Promise<GridPlaneDto> {
  const gridDto = gridPlaneDto.grids?.[0] ?? {};
  const custom = gridDto.state?.custom;
  const tableName = custom?.[CONTENT_FORM_CUSTOM_TABLE_NAME];
  const dynamics = await dynamicLoad(request, typeof tableName === 'string' && tableName !== '' ? tableName : undefined);
  // Filter-Sort-Page: only the page state is used (no columns, so no filter or sort). Not its selectedRowIndex: the rendered rows are the form's, not the paged ones.
  const { rows: pageDynamics, state: fspState } = gridFsp(dynamics, [], gridDto.state);

  const count = (key: string) => designFormCount(typeof custom?.[key] === 'string' ? custom[key] : undefined);
  const rowCount = count(CONTENT_FORM_CUSTOM_ROW_COUNT);
  const columnNames = Array.from({ length: count(CONTENT_FORM_CUSTOM_COLUMN_COUNT) }, (_, columnIndex) => indexToColumnNameExcel(columnIndex));

  // FieldName of each cell (owner designFormCellPropertyOwner), undefined if missing or empty.
  const bandName = custom?.[CONTENT_FORM_CUSTOM_BAND_NAME];
  const cellProperties = typeof bandName === 'string' && bandName !== '' ? await designFormCellPropertyLoadAll(request, bandName) : [];
  const fieldName = (rowIndex: number, columnName: string): string | undefined => {
    const { ownerName } = designFormCellPropertyOwner(String(bandName), rowIndex, columnName);
    return cellProperties.find((property) => property.ownerName === ownerName && property.propertyName === 'FieldName')?.propertyValue || undefined;
  };
  // Value row text: the dynamic row's value of the cell's FieldName ("" if missing), or "Empty" if the cell has no FieldName.
  const valueText = (dynamic: Record<string, unknown>, formRowIndex: number, columnName: string): string => {
    const name = fieldName(formRowIndex, columnName);
    return name !== undefined ? gridCellText(dynamic[name], {}) : 'Empty';
  };

  // No columnName on the header cells: clicking them doesn't sort and they have no filter button.
  const headerRow: GridRowDto = { cells: columnNames.map((columnName) => gridHeaderCell(undefined, undefined, columnName)) };
  // The form is repeated for each dynamic row of the page; all its cells get rowIndex of that dynamic row (so the whole repetition is selected together).
  // Each form row renders as two rows: its FieldNames ("Cell" if missing), then their values.
  const rows: GridRowDto[] = (pageDynamics as Record<string, unknown>[]).flatMap((dynamic, rowIndex) => Array.from({ length: rowCount }, (_, formRowIndex) => [
    { cells: columnNames.map((columnName): GridCellDto => ({ cellEnum: GridCellEnum.Label, text: fieldName(formRowIndex, columnName) ?? 'Cell', rowIndex, columnName })) },
    { cells: columnNames.map((columnName): GridCellDto => ({ cellEnum: GridCellEnum.Label, text: valueText(dynamic, formRowIndex, columnName), rowIndex, columnName })) },
  ]).flat());

  // Command (e.g. New or Save of the bar) is transient: not sent back, so it isn't re-processed on a later request.
  return {
    ...gridPlaneDto,
    grids: [{ tables: gridTables([], columnNames.length > 0 && rowCount > 0 ? [headerRow, ...rows] : [], [gridBarRow()]), state: { ...fspState, selectedRowIndex: undefined, custom } }],
  };
}

/** Returns the properties shown in the Properties grid: those of cell of the Form grid if one is selected, otherwise those of band; none if no band is selected. */
async function gridDesignBandFormPropertyLoadAll(request: Request, band: DesignBandDto | undefined, cell: DesignFormCell | undefined): Promise<PropertyDto[]> {
  if (!band?.name) {
    return [];
  }
  return cell !== undefined ? designFormCellPropertyLoad(request, band.name, cell.rowIndex, cell.columnName) : designBandPropertyLoad(request, band.name);
}

/** Returns the band of the selected row of the design band grid (its rowKey is the _id), or undefined if no row is selected. */
async function gridDesignBandSelectedLoad(request: Request, gridDto: GridDto): Promise<DesignBandDto | undefined> {
  const selected = gridDto.state?.selectedRowIndex;
  const rowKey = selected !== undefined ? gridDto.state?.rowKeys?.[selected] : undefined;
  return rowKey !== undefined ? (await designBandLoadByIds(request, [rowKey]))[0] : undefined;
}

async function gridDesignBandLoad(request: Request, gridDto: GridDto): Promise<GridDto> {
  // Selection is by rowIndex: remember it by rowKey so it can be mapped onto the reloaded rows (deleted rows drop out).
  const selectedMultiRowKeys = new Set(gridSelectedMultiRowKeys(gridDto));

  // Delete confirmation (opened by a row's Delete button or the toolbar's DeleteMulti button below) lives at gridDto.planes[1].grids[0] (planes[0] is the lookup), carrying GridStateDto.custom.rowKeys.
  const confirmGridDto = gridDto.planes?.[1]?.grids?.[0];
  if (confirmGridDto !== undefined) {
    // Its Cancel button (GridCustomEnum.Cancel) closes the dialog in App.Web without a server call.
    if (gridIsCommand(confirmGridDto, 'Yes')) {
      const rowKeys = confirmGridDto.state?.custom?.rowKeys;
      if (Array.isArray(rowKeys)) {
        await designBandDelete(request, rowKeys.filter((rowKey): rowKey is string => typeof rowKey === 'string'));
      }
      gridDto.planes = undefined;
    } else {
      // Rows aren't sent back by the client: rebuild them so the dialog stays visible across other commands.
      gridDto.planes = [null, { grids: [{ ...gridDebugDeleteConfirm(confirmGridDto.state?.custom?.rowKeys), command: undefined }] }];
    }
  }

  if (gridIsCommand(gridDto, 'Delete')) {
    const rowIndex = gridDto.command?.rowIndex;
    const rowKey = rowIndex !== undefined ? gridDto.state?.rowKeys?.[rowIndex] : undefined;
    if (rowKey !== undefined) {
      gridDto.planes = [null, { grids: [gridDebugDeleteConfirm([rowKey])] }];
    }
  }

  if (gridIsCommand(gridDto, 'DeleteMulti') && selectedMultiRowKeys.size > 0) {
    gridDto.planes = [null, { grids: [gridDebugDeleteConfirm([...selectedMultiRowKeys])] }];
  }

  if (gridDto.command?.commandEnum === GridCommandEnum.Save) {
    await gridDesignBandSaveUpdate(request, gridDto);
    await gridDesignBandSaveInsert(request, gridDto);
  }

  const allBands = await designBandLoad(request);

  // Filter Multi Ok: apply the chosen texts (GridStateDto.filterMultis) before the rows are built.
  gridFilterMultiOk(gridDto, DESIGN_BAND_COLUMNS.columns ?? [], allBands);

  // Filter-Sort-Page: bands holds only the rows of the current page.
  const { rows: bands, state: fspState } = gridFsp(allBands, DESIGN_BAND_COLUMNS.columns ?? [], gridDto.state);

  const columns = gridColumns(DESIGN_BAND_COLUMNS.columns ?? []);

  const headerRow: GridRowDto = {
    cells: [...columns.map((column) => gridHeaderCell(column.columnName, gridDto.state?.sort)), { cellEnum: GridCellEnum.Header, text: 'Command' }],
  };
  const rows: GridRowDto[] = bands.map((band, rowIndex) => ({
    cells: [
      ...columns.map(
        (column, columnIndex): GridCellDto => ({
          cellEnum: GridCellEnum.Edit,
          text: gridCellText(band[column.columnName as keyof DesignBandDto], column),
          rowIndex,
          columnName: column.columnName,
          isSelectMulti: columnIndex === 0 ? true : undefined,
        }),
      ),
      {
        cellEnum: GridCellEnum.Custom,
        customs: [{ text: 'Delete', name: 'Delete', customEnum: GridCustomEnum.Button, rowIndex } satisfies GridCustomDto],
        rowIndex,
      },
    ],
  }));

  // rowKey is the _id (ObjectId hex), since name is not sent to App.Web.
  const rowKeys: string[] = bands.map((band) => band._id?.toHexString() ?? '');
  const isSelectedMulti = rowKeys.map((rowKey) => selectedMultiRowKeys.has(rowKey));
  const findRow = gridFindRow([...columns.map((column) => column.columnName), undefined]);

  const toolbarRow: GridRowDto = {
    cells: [
      {
        cellEnum: GridCellEnum.Custom,
        customs: [
          {
            text: 'Delete',
            name: 'DeleteMulti',
            customEnum: GridCustomEnum.Button,
            isDisabled: !isSelectedMulti.some((isSelected) => isSelected),
          },
        ],
      },
    ],
  };

  const result: GridDto = {
    ...gridDto,
    title: 'Design Band',
    tables: gridTables([toolbarRow], [headerRow, findRow, ...rows], [gridBarRow()]),
    state: { ...gridDto.state, ...fspState, rowKeys, isSelectedMulti },
    setting: { isSelectPatch: true, isSelectMultiPatch: true },
  };

  if (gridDto.command?.commandEnum === GridCommandEnum.New) {
    gridDesignBandNew(result);
  }

  // Lookup (planes[0]): Filter Multi (opened by planeDesignPatch, kept open while planes[0].planeName is filterMulti).
  gridLookupSet(result, gridFilterMultiLoad(gridDto, DESIGN_BAND_COLUMNS.columns ?? [], allBands));

  // Command is transient: clear it so it isn't re-processed on a later request.
  result.command = undefined;

  return result;
}

/**
 * band (the selected row of the design band grid) gets its properties synced (designBandPropertySync), or, if cell (the selected cell of the Form grid) is set,
 * the properties of that cell (designFormCellPropertySync), which then are the rows; undefined band shows no rows.
 */
async function gridDesignBandFormPropertyLoad(request: Request, gridDto: GridDto, band: DesignBandDto | undefined, cell: DesignFormCell | undefined): Promise<GridDto> {
  if (gridDto.command?.commandEnum === GridCommandEnum.Save) {
    await gridDesignBandFormPropertySaveUpdate(request, gridDto);
  }

  if (band?.name && cell !== undefined) {
    await designFormCellPropertySync(request, band.name, cell.rowIndex, cell.columnName);
  } else if (band !== undefined) {
    await designBandPropertySync(request, band);
  }
  const allProperties = await gridDesignBandFormPropertyLoadAll(request, band, cell);

  // Filter Multi Ok: apply the chosen texts (GridStateDto.filterMultis) before the rows are built.
  gridFilterMultiOk(gridDto, DESIGN_PROPERTY_COLUMNS.columns ?? [], allProperties);

  // Filter-Sort-Page: properties holds only the rows of the current page.
  const { rows: properties, state: fspState } = gridFsp(allProperties, DESIGN_PROPERTY_COLUMNS.columns ?? [], gridDto.state);

  const headerRow: GridRowDto = {
    cells: gridColumns(DESIGN_PROPERTY_COLUMNS.columns ?? []).map((column) => gridHeaderCell(column.columnName, gridDto.state?.sort)),
  };
  const rows: GridRowDto[] = properties.map((property, rowIndex) => ({
    cells: gridColumns(DESIGN_PROPERTY_COLUMNS.columns ?? []).map(
      (column): GridCellDto => ({
        cellEnum: column.columnName === ('propertyValue' satisfies keyof PropertyDto) ? GridCellEnum.Edit : GridCellEnum.Label,
        text: gridCellText(property[column.columnName as keyof PropertyDto], column),
        rowIndex,
        columnName: column.columnName,
      }),
    ),
  }));

  // rowKey is the _id (ObjectId hex), since name is not sent to App.Web.
  const rowKeys: string[] = properties.map((property) => property._id?.toHexString() ?? '');
  const findRow = gridFindRow(gridColumns(DESIGN_PROPERTY_COLUMNS.columns ?? []).map((column) => column.columnName));

  const result: GridDto = {
    ...gridDto,
    title: 'Properties',
    tables: gridTables([], [headerRow, findRow, ...rows], [gridBarRow()]),
    state: { ...gridDto.state, ...fspState, rowKeys },
    // No New: the rows are generated by designBandPropertySync.
    setting: { isNewHide: true },
  };

  // Lookup (planes[0]): Filter Multi (opened by planeDesignPatch, kept open while planes[0].planeName is filterMulti).
  gridLookupSet(result, gridFilterMultiLoad(gridDto, DESIGN_PROPERTY_COLUMNS.columns ?? [], allProperties));

  // Command is transient: clear it so it isn't re-processed on a later request.
  result.command = undefined;

  return result;
}

/**
 * Patches the "design" plane's grids (design band grid GridPlaneDto.grids[0], Properties grid grids[1], Form grid grids[2]):
 * GridCommandEnum.FilterMulti opens the Filter Multi lookup (distinct texts of its column);
 * GridCommandEnum.Select of a design band grid row replaces the Properties grid with the properties of the selected band and the Form grid with its preview (no cell selected);
 * GridCommandEnum.Select of a Form grid cell (GridSettingDto.isSelectPatch, isSelectColumnPatch) replaces the Properties grid with the properties of that cell;
 * any other command (MultiClick) enables/disables the design band grid's DeleteMulti button.
 */
export async function planeDesignPatch(request: Request, gridPlaneDto: GridPlaneDto): Promise<GridPlaneDto> {
  const gridDto = gridPlaneDto.grids?.[0] ?? {};
  const propertyGridDto = gridPlaneDto.grids?.[1] ?? {};
  const formGridDto = gridPlaneDto.grids?.[2] ?? {};
  // Other rows are shown: start on the first page with no selection, sort or filter, and drop the pending command, unsaved modifies and an open lookup.
  const propertyGridDtoSelect: GridDto = {
    ...propertyGridDto,
    command: undefined,
    modifies: undefined,
    planes: undefined,
    state: { ...propertyGridDto.state, selectedRowIndex: undefined, selectedColumnName: undefined, isSelectedMulti: undefined, pageIndex: 0, sort: undefined, filters: undefined, filterMultis: undefined },
  };
  if (gridDto.command?.commandEnum === GridCommandEnum.Select) {
    // The incoming state carries selected and the rowKeys of the loaded rows.
    const band = await gridDesignBandSelectedLoad(request, gridDto);
    // The Form grid is rebuilt with no selection, so the Properties grid shows the properties of the band.
    const grid = await gridDesignBandFormPropertyLoad(request, propertyGridDtoSelect, band, undefined);
    const formGrid = await gridDesignFormLoad(request, band, {});
    return {
      ...gridPlaneDto,
      grids: [{}, { patches: [{ patchEnum: GridPatchEnum.Grid, grid } satisfies GridPatchDto] }, { patches: [{ patchEnum: GridPatchEnum.Grid, grid: formGrid } satisfies GridPatchDto] }],
    };
  }
  if (formGridDto.command?.commandEnum === GridCommandEnum.Select) {
    // The Form grid keeps its selection (App.Web keeps the sent state), only the Properties grid is replaced.
    const band = await gridDesignBandSelectedLoad(request, gridDto);
    const cell = await gridDesignFormSelectedLoad(request, band, formGridDto);
    const grid = await gridDesignBandFormPropertyLoad(request, propertyGridDtoSelect, band, cell);
    return { ...gridPlaneDto, grids: [{}, { patches: [{ patchEnum: GridPatchEnum.Grid, grid } satisfies GridPatchDto] }, {}] };
  }
  if (gridDto.command?.commandEnum === GridCommandEnum.FilterMulti) {
    const lookupPlane = gridFilterMultiLoad(gridDto, DESIGN_BAND_COLUMNS.columns ?? [], await designBandLoad(request));
    return { ...gridPlaneDto, grids: [{ patches: [{ patchEnum: GridPatchEnum.Lookup, planeName: lookupPlane?.planeName, lookup: lookupPlane?.grids?.[0] } satisfies GridPatchDto] }, {}, {}] };
  }
  if (propertyGridDto.command?.commandEnum === GridCommandEnum.FilterMulti) {
    const band = await gridDesignBandSelectedLoad(request, gridDto);
    const cell = await gridDesignFormSelectedLoad(request, band, formGridDto);
    const lookupPlane = gridFilterMultiLoad(propertyGridDto, DESIGN_PROPERTY_COLUMNS.columns ?? [], await gridDesignBandFormPropertyLoadAll(request, band, cell));
    return { ...gridPlaneDto, grids: [{}, { patches: [{ patchEnum: GridPatchEnum.Lookup, planeName: lookupPlane?.planeName, lookup: lookupPlane?.grids?.[0] } satisfies GridPatchDto] }, {}] };
  }
  return { ...gridPlaneDto, grids: [await gridPatchDeleteMulti(request, gridDto), {}, {}] };
}

/** Saves the modified propertyValue cells; RowCount, ColumnCount, ColumnSpan and RowSpan must be whole numbers (or empty). */
async function gridDesignBandFormPropertySaveUpdate(request: Request, gridDto: GridDto): Promise<void> {
  const modifies = (gridDto.modifies ?? []).filter((modify) => !modify.isNew);
  const rowKeys = gridDto.state?.rowKeys ?? [];

  const ids = [
    ...new Set(
      modifies
        .map((modify) => (modify.rowIndex !== undefined ? rowKeys[modify.rowIndex] : undefined))
        .filter((rowKey): rowKey is string => rowKey !== undefined),
    ),
  ];

  const properties = await designBandFormPropertyLoadByIds(request, ids);

  for (const modify of modifies) {
    if (modify.rowIndex === undefined || modify.columnName !== ('propertyValue' satisfies keyof PropertyDto) || modify.cellEnum !== GridCellEnum.Edit) {
      continue;
    }

    const rowKey = rowKeys[modify.rowIndex];
    const property = properties.find((property) => property._id?.toHexString() === rowKey);
    if (property) {
      const propertyValue = (modify.textModified ?? '').trim();
      if (DESIGN_BAND_PROPERTY_NUMBER_NAMES.has(property.propertyName ?? '') && propertyValue !== '' && !Number.isInteger(Number(propertyValue))) {
        throw new Error(`${property.propertyName} "${propertyValue}" is not a whole number!`);
      }
      property.propertyValue = propertyValue;
    }
  }

  await designBandFormPropertyUpdate(request, properties);
}

async function gridDesignBandSaveUpdate(request: Request, gridDto: GridDto): Promise<void> {
  const modifies = (gridDto.modifies ?? []).filter((modify) => !modify.isNew);
  const rowKeys = gridDto.state?.rowKeys ?? [];

  const ids = [
    ...new Set(
      modifies
        .map((modify) => (modify.rowIndex !== undefined ? rowKeys[modify.rowIndex] : undefined))
        .filter((rowKey): rowKey is string => rowKey !== undefined),
    ),
  ];

  const bands = await designBandLoadByIds(request, ids);

  const columns = gridColumns(DESIGN_BAND_COLUMNS.columns ?? []);

  for (const modify of modifies) {
    const column = columns.find((column) => column.columnName === modify.columnName);
    if (modify.rowIndex === undefined || modify.columnName === undefined || modify.cellEnum !== GridCellEnum.Edit || column === undefined) {
      continue;
    }

    const rowKey = rowKeys[modify.rowIndex];
    const band = bands.find((band) => band._id?.toHexString() === rowKey);
    if (band) {
      (band as unknown as Record<string, unknown>)[modify.columnName] = gridCellValue(modify.textModified, column);
    }
  }

  await designBandUpdate(request, bands);
}

async function gridDesignBandSaveInsert(request: Request, gridDto: GridDto): Promise<void> {
  const modifies = (gridDto.modifies ?? []).filter((modify) => modify.isNew);

  const columns = gridColumns(DESIGN_BAND_COLUMNS.columns ?? []);

  const bandsByRowIndex = new Map<number, DesignBandDto>();

  for (const modify of modifies) {
    const column = columns.find((column) => column.columnName === modify.columnName);
    if (modify.rowIndex === undefined || modify.columnName === undefined || modify.cellEnum !== GridCellEnum.Edit || column === undefined) {
      continue;
    }

    const band = bandsByRowIndex.get(modify.rowIndex) ?? {};
    (band as unknown as Record<string, unknown>)[modify.columnName] = gridCellValue(modify.textModified, column);
    bandsByRowIndex.set(modify.rowIndex, band);
  }

  await designBandInsert(request, [...bandsByRowIndex.values()]);
}

/** Appends one empty, editable new row to the data table (GridDto.tables[1]). */
function gridDesignBandNew(gridDto: GridDto): void {
  const dataTable = gridDto.tables?.[1];
  if (dataTable === undefined) {
    return;
  }
  const rows = dataTable.rows ?? [];
  const rowIndex = rows.length;

  const newRow: GridRowDto = {
    cells: gridColumns(DESIGN_BAND_COLUMNS.columns ?? []).map(
      (column): GridCellDto => ({
        cellEnum: GridCellEnum.Edit,
        columnName: column.columnName,
        placeHolder: 'New',
        rowIndex,
        isNew: true,
      }),
    ),
  };

  dataTable.rows = [...rows, newRow];
}

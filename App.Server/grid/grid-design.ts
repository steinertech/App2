/** The names of LayoutBandEnum, e.g. "Header". */
const DESIGN_BAND_ENUM_NAMES = Object.keys(LayoutBandEnum).filter((key) => isNaN(Number(key)));

/** Parses a LayoutBandEnum name (case-insensitive, e.g. "header") or number (e.g. "1"). "" is LayoutBandEnum.None. */
function designBandEnumFromText(text: string): LayoutBandEnum {
  const value = text.trim();
  if (value === '') {
    return LayoutBandEnum.None;
  }
  const name = DESIGN_BAND_ENUM_NAMES.find((name) => name.toLowerCase() === value.toLowerCase());
  const result = name !== undefined ? LayoutBandEnum[name as keyof typeof LayoutBandEnum] : Number(value);
  if (!Number.isInteger(result) || LayoutBandEnum[result] === undefined) {
    throw new Error(`Band "${text}" is not one of: ${DESIGN_BAND_ENUM_NAMES.join(', ')}!`);
  }
  return result;
}

/** Parses a whole number. "" is 0. */
function designSortFromText(text: string): number {
  const value = text.trim();
  if (value === '') {
    return 0;
  }
  const result = Number(value);
  if (!Number.isInteger(result)) {
    throw new Error(`Sort "${text}" is not a whole number!`);
  }
  return result;
}

/** DesignBandPropertyDto.propertyName values whose propertyValue must be a whole number (or empty). */
const DESIGN_PROPERTY_NUMBER_NAMES = new Set(['RowCount', 'ColumnCount']);

// name is not a column, so it's never sent to App.Web (designBandInsert sets it to a random UUID).
const DESIGN_BAND_COLUMNS: GridConfigDto = {
  columns: [
    { columnName: 'layoutName' satisfies keyof DesignBandDto, text: 'Layout', typeEnum: GridConfigTypeEnum.Text },
    {
      columnName: 'bandEnum' satisfies keyof DesignBandDto,
      text: 'Band',
      typeEnum: GridConfigTypeEnum.Number,
      valueToText: (value) => LayoutBandEnum[value as LayoutBandEnum] ?? String(value),
      valueFromText: designBandEnumFromText,
    },
    { columnName: 'sort' satisfies keyof DesignBandDto, typeEnum: GridConfigTypeEnum.Number, valueFromText: designSortFromText },
  ],
};

// bandName (the foreign key, a UUID) is not a column; propertyName is generated by designPropertySync, so only propertyValue is editable.
const DESIGN_PROPERTY_COLUMNS: GridConfigDto = {
  columns: [
    { columnName: 'propertyName' satisfies keyof DesignBandPropertyDto, text: 'Property', typeEnum: GridConfigTypeEnum.Text },
    { columnName: 'propertyValue' satisfies keyof DesignBandPropertyDto, text: 'Value', typeEnum: GridConfigTypeEnum.Text },
  ],
};

/**
 * Loads the "design" plane: the design band grid (GridPlaneDto.grids[0])
 * and the Properties grid (grids[1]) with the DesignBandPropertyDto rows of the band selected in grids[0] (no rows if none is selected).
 */
export async function planeDesignLoad(request: Request, gridPlaneDto: GridPlaneDto): Promise<GridPlaneDto> {
  // The Properties grid depends on the reloaded design band grid (its selected row), so it is built afterwards.
  const gridDto = await gridDesignBandLoad(request, gridPlaneDto.grids?.[0] ?? {});
  const propertyGridDto = await gridDesignPropertyLoad(request, gridPlaneDto.grids?.[1] ?? {}, await gridDesignBandSelected(request, gridDto));
  return { ...gridPlaneDto, grids: [gridDto, propertyGridDto] };
}

/** Returns the band of the selected row of the design band grid (its rowKey is the _id), or undefined if no row is selected. */
async function gridDesignBandSelected(request: Request, gridDto: GridDto): Promise<DesignBandDto | undefined> {
  const selected = gridDto.state?.selected;
  const rowKey = selected !== undefined ? gridDto.state?.rowKeys?.[selected] : undefined;
  return rowKey !== undefined ? (await designBandLoadByIds(request, [rowKey]))[0] : undefined;
}

async function gridDesignBandLoad(request: Request, gridDto: GridDto): Promise<GridDto> {
  if (gridDto.command?.commandEnum === GridCommandEnum.Save) {
    await gridDesignBandSaveUpdate(request, gridDto);
    await gridDesignBandSaveInsert(request, gridDto);
  }

  const allBands = await designBandLoad(request);

  // Filter Multi Ok: apply the chosen texts (GridStateDto.filterMultis) before the rows are built.
  gridFilterMultiOk(gridDto, DESIGN_BAND_COLUMNS.columns ?? [], allBands);

  // Filter-Sort-Page: bands holds only the rows of the current page.
  const { rows: bands, state: fspState } = gridFsp(allBands, DESIGN_BAND_COLUMNS.columns ?? [], gridDto.state);

  const headerRow: GridRowDto = {
    cells: gridColumns(DESIGN_BAND_COLUMNS.columns ?? []).map((column) => gridHeaderCell(column.columnName, gridDto.state?.sort)),
  };
  const rows: GridRowDto[] = bands.map((band, rowIndex) => ({
    cells: gridColumns(DESIGN_BAND_COLUMNS.columns ?? []).map(
      (column): GridCellDto => ({
        cellEnum: GridCellEnum.Edit,
        text: gridCellText(band[column.columnName as keyof DesignBandDto], column),
        rowIndex,
        columnName: column.columnName,
      }),
    ),
  }));

  // rowKey is the _id (ObjectId hex), since name is not sent to App.Web.
  const rowKeys: string[] = bands.map((band) => band._id?.toHexString() ?? '');
  const findRow = gridFindRow(gridColumns(DESIGN_BAND_COLUMNS.columns ?? []).map((column) => column.columnName));

  const result: GridDto = {
    ...gridDto,
    title: 'Design Band',
    tables: gridTables([], [headerRow, findRow, ...rows], [gridBarRow()]),
    state: { ...gridDto.state, ...fspState, rowKeys },
    setting: { isSelectPatch: true },
  };

  if (gridDto.command?.commandEnum === GridCommandEnum.New) {
    gridDesignBandNew(result);
  }

  // Lookup (planes[0]): Filter Multi (opened by planeDesignPatch, kept open while planes[0].planeName is filterMulti).
  gridLookupSet(result, gridFilterMultiLoad(gridDto, DESIGN_BAND_COLUMNS.columns ?? [], allBands));

  // Command is transient: clear it so it isn't re-processed on a later request.
  result.command = undefined;

  return result;
}

/** band (the selected row of the design band grid) gets its properties synced (designPropertySync), then filters the rows; undefined shows no rows. */
async function gridDesignPropertyLoad(request: Request, gridDto: GridDto, band: DesignBandDto | undefined): Promise<GridDto> {
  if (gridDto.command?.commandEnum === GridCommandEnum.Save) {
    await gridDesignPropertySaveUpdate(request, gridDto);
  }

  if (band !== undefined) {
    await designPropertySync(request, band);
  }
  const allProperties = band?.name ? await designPropertyLoad(request, band.name) : [];

  // Filter Multi Ok: apply the chosen texts (GridStateDto.filterMultis) before the rows are built.
  gridFilterMultiOk(gridDto, DESIGN_PROPERTY_COLUMNS.columns ?? [], allProperties);

  // Filter-Sort-Page: properties holds only the rows of the current page.
  const { rows: properties, state: fspState } = gridFsp(allProperties, DESIGN_PROPERTY_COLUMNS.columns ?? [], gridDto.state);

  const headerRow: GridRowDto = {
    cells: gridColumns(DESIGN_PROPERTY_COLUMNS.columns ?? []).map((column) => gridHeaderCell(column.columnName, gridDto.state?.sort)),
  };
  const rows: GridRowDto[] = properties.map((property, rowIndex) => ({
    cells: gridColumns(DESIGN_PROPERTY_COLUMNS.columns ?? []).map(
      (column): GridCellDto => ({
        cellEnum: column.columnName === ('propertyValue' satisfies keyof DesignBandPropertyDto) ? GridCellEnum.Edit : GridCellEnum.Label,
        text: gridCellText(property[column.columnName as keyof DesignBandPropertyDto], column),
        rowIndex,
        columnName: column.columnName,
      }),
    ),
  }));

  // rowKey is the _id (ObjectId hex), since name is not sent to App.Web.
  const rowKeys: string[] = properties.map((property) => property._id?.toHexString() ?? '');
  const findRow = gridFindRow(gridColumns(DESIGN_PROPERTY_COLUMNS.columns ?? []).map((column) => column.columnName));

  const result: GridDto = {
    ...gridDto,
    title: 'Properties',
    tables: gridTables([], [headerRow, findRow, ...rows], [gridBarRow()]),
    state: { ...gridDto.state, ...fspState, rowKeys },
    // No New: the rows are generated by designPropertySync.
    setting: { isNewHide: true },
  };

  // Lookup (planes[0]): Filter Multi (opened by planeDesignPatch, kept open while planes[0].planeName is filterMulti).
  gridLookupSet(result, gridFilterMultiLoad(gridDto, DESIGN_PROPERTY_COLUMNS.columns ?? [], allProperties));

  // Command is transient: clear it so it isn't re-processed on a later request.
  result.command = undefined;

  return result;
}

/**
 * Patches the "design" plane's grids (design band grid GridPlaneDto.grids[0], Properties grid grids[1]):
 * GridCommandEnum.FilterMulti opens the Filter Multi lookup (distinct texts of its column);
 * GridCommandEnum.Select of a design band grid row replaces the Properties grid with the properties of the selected band.
 */
export async function planeDesignPatch(request: Request, gridPlaneDto: GridPlaneDto): Promise<GridPlaneDto> {
  const gridDto = gridPlaneDto.grids?.[0] ?? {};
  const propertyGridDto = gridPlaneDto.grids?.[1] ?? {};
  if (gridDto.command?.commandEnum === GridCommandEnum.Select) {
    // Other rows are shown: start on the first page with no selection, sort or filter, and drop the pending command, unsaved modifies and an open lookup.
    const propertyGridDtoSelect: GridDto = {
      ...propertyGridDto,
      command: undefined,
      modifies: undefined,
      planes: undefined,
      state: { ...propertyGridDto.state, selected: undefined, isSelectedMulti: undefined, pageIndex: 0, sort: undefined, filters: undefined, filterMultis: undefined },
    };
    // The incoming state carries selected and the rowKeys of the loaded rows.
    const grid = await gridDesignPropertyLoad(request, propertyGridDtoSelect, await gridDesignBandSelected(request, gridDto));
    return { ...gridPlaneDto, grids: [{}, { patches: [{ patchEnum: GridPatchEnum.Grid, grid } satisfies GridPatchDto] }] };
  }
  if (gridDto.command?.commandEnum === GridCommandEnum.FilterMulti) {
    const lookupPlane = gridFilterMultiLoad(gridDto, DESIGN_BAND_COLUMNS.columns ?? [], await designBandLoad(request));
    return { ...gridPlaneDto, grids: [{ patches: [{ patchEnum: GridPatchEnum.Lookup, planeName: lookupPlane?.planeName, lookup: lookupPlane?.grids?.[0] } satisfies GridPatchDto] }, {}] };
  }
  if (propertyGridDto.command?.commandEnum === GridCommandEnum.FilterMulti) {
    const band = await gridDesignBandSelected(request, gridDto);
    const lookupPlane = gridFilterMultiLoad(propertyGridDto, DESIGN_PROPERTY_COLUMNS.columns ?? [], band?.name ? await designPropertyLoad(request, band.name) : []);
    return { ...gridPlaneDto, grids: [{}, { patches: [{ patchEnum: GridPatchEnum.Lookup, planeName: lookupPlane?.planeName, lookup: lookupPlane?.grids?.[0] } satisfies GridPatchDto] }] };
  }
  return { ...gridPlaneDto, grids: [{}, {}] };
}

/** Saves the modified propertyValue cells; RowCount and ColumnCount must be whole numbers (or empty). */
async function gridDesignPropertySaveUpdate(request: Request, gridDto: GridDto): Promise<void> {
  const modifies = (gridDto.modifies ?? []).filter((modify) => !modify.isNew);
  const rowKeys = gridDto.state?.rowKeys ?? [];

  const ids = [
    ...new Set(
      modifies
        .map((modify) => (modify.rowIndex !== undefined ? rowKeys[modify.rowIndex] : undefined))
        .filter((rowKey): rowKey is string => rowKey !== undefined),
    ),
  ];

  const properties = await designPropertyLoadByIds(request, ids);

  for (const modify of modifies) {
    if (modify.rowIndex === undefined || modify.columnName !== ('propertyValue' satisfies keyof DesignBandPropertyDto) || modify.cellEnum !== GridCellEnum.Edit) {
      continue;
    }

    const rowKey = rowKeys[modify.rowIndex];
    const property = properties.find((property) => property._id?.toHexString() === rowKey);
    if (property) {
      const propertyValue = (modify.textModified ?? '').trim();
      if (DESIGN_PROPERTY_NUMBER_NAMES.has(property.propertyName ?? '') && propertyValue !== '' && !Number.isInteger(Number(propertyValue))) {
        throw new Error(`${property.propertyName} "${propertyValue}" is not a whole number!`);
      }
      property.propertyValue = propertyValue;
    }
  }

  await designPropertyUpdate(request, properties);
}

async function gridDesignBandSaveUpdate(request: Request, gridDto: GridDto): Promise<void> {
  const modifies = (gridDto.modifies ?? []).filter((modify) => !modify.isNew);
  const rowKeys = gridDto.state?.rowKeys ?? [];

  const ids = [
    ...new Set(
      modifies
        .map((modify) => (modify.rowIndex !== undefined ? rowKeys[modify.rowIndex] : undefined))
        .filter((rowKey): rowKey is string => rowKey !== undefined),
    ),
  ];

  const bands = await designBandLoadByIds(request, ids);

  const columns = gridColumns(DESIGN_BAND_COLUMNS.columns ?? []);

  for (const modify of modifies) {
    const column = columns.find((column) => column.columnName === modify.columnName);
    if (modify.rowIndex === undefined || modify.columnName === undefined || modify.cellEnum !== GridCellEnum.Edit || column === undefined) {
      continue;
    }

    const rowKey = rowKeys[modify.rowIndex];
    const band = bands.find((band) => band._id?.toHexString() === rowKey);
    if (band) {
      (band as unknown as Record<string, unknown>)[modify.columnName] = gridCellValue(modify.textModified, column);
    }
  }

  await designBandUpdate(request, bands);
}

async function gridDesignBandSaveInsert(request: Request, gridDto: GridDto): Promise<void> {
  const modifies = (gridDto.modifies ?? []).filter((modify) => modify.isNew);

  const columns = gridColumns(DESIGN_BAND_COLUMNS.columns ?? []);

  const bandsByRowIndex = new Map<number, DesignBandDto>();

  for (const modify of modifies) {
    const column = columns.find((column) => column.columnName === modify.columnName);
    if (modify.rowIndex === undefined || modify.columnName === undefined || modify.cellEnum !== GridCellEnum.Edit || column === undefined) {
      continue;
    }

    const band = bandsByRowIndex.get(modify.rowIndex) ?? {};
    (band as unknown as Record<string, unknown>)[modify.columnName] = gridCellValue(modify.textModified, column);
    bandsByRowIndex.set(modify.rowIndex, band);
  }

  await designBandInsert(request, [...bandsByRowIndex.values()]);
}

/** Appends one empty, editable new row to the data table (GridDto.tables[1]). */
function gridDesignBandNew(gridDto: GridDto): void {
  const dataTable = gridDto.tables?.[1];
  if (dataTable === undefined) {
    return;
  }
  const rows = dataTable.rows ?? [];
  const rowIndex = rows.length;

  const newRow: GridRowDto = {
    cells: gridColumns(DESIGN_BAND_COLUMNS.columns ?? []).map(
      (column): GridCellDto => ({
        cellEnum: GridCellEnum.Edit,
        columnName: column.columnName,
        placeHolder: 'New',
        rowIndex,
        isNew: true,
      }),
    ),
  };

  dataTable.rows = [...rows, newRow];
}

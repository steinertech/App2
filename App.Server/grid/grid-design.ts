/** The names of ContentBandEnum, e.g. "Header". */
const DESIGN_BAND_ENUM_NAMES = Object.keys(ContentBandEnum).filter((key) => isNaN(Number(key)));

/** Parses a ContentBandEnum name (case-insensitive, e.g. "header") or number (e.g. "1"). "" is ContentBandEnum.None. */
function designBandEnumFromText(text: string): ContentBandEnum {
  const value = text.trim();
  if (value === '') {
    return ContentBandEnum.None;
  }
  const name = DESIGN_BAND_ENUM_NAMES.find((name) => name.toLowerCase() === value.toLowerCase());
  const result = name !== undefined ? ContentBandEnum[name as keyof typeof ContentBandEnum] : Number(value);
  if (!Number.isInteger(result) || ContentBandEnum[result] === undefined) {
    throw new Error(`Band "${text}" is not one of: ${DESIGN_BAND_ENUM_NAMES.join(', ')}!`);
  }
  return result;
}

/** Parses a whole number. "" is 0. */
function designSortFromText(text: string): number {
  const value = text.trim();
  if (value === '') {
    return 0;
  }
  const result = Number(value);
  if (!Number.isInteger(result)) {
    throw new Error(`Sort "${text}" is not a whole number!`);
  }
  return result;
}

